export function getStatusIconUrl(effectTypeOrName?: string): string {
  if (!effectTypeOrName) return STATUS_ICON_URLS.buff_atk;
  const key = effectTypeOrName.toLowerCase().trim().replace(/[\s-]/g, '_');

  if (STATUS_ICON_URLS[key]) {
    return STATUS_ICON_URLS[key];
  }

  // Typhon Ephemeros signature skill icons
  if (key.includes('blaze_of_etna') || key.includes('armor_of_ashen')) {
    return STATUS_ICON_URLS.buster_up;
  }
  if (key.includes('black_wings')) {
    return STATUS_ICON_URLS.crit_dmg;
  }
  if (key.includes('let_this_become_a_prayer') || key.includes('prayer')) {
    return STATUS_ICON_URLS.np_charge;
  }
  if (key.includes('overcharge')) {
    return STATUS_ICON_URLS.overcharge_up;
  }

  // Substring matching helper
  if (key.includes('atk_up') || key.includes('attack_up') || (key.includes('atk') && !key.includes('down'))) {
    return STATUS_ICON_URLS.buff_atk;
  }
  if (key.includes('atk_down') || key.includes('attack_down')) {
    return STATUS_ICON_URLS.atk_down;
  }
  if (key.includes('def_up') || key.includes('defense_up') || (key.includes('def') && !key.includes('down'))) {
    return STATUS_ICON_URLS.buff_def;
  }
  if (key.includes('def_down') || key.includes('defense_down')) {
    return STATUS_ICON_URLS.def_down;
  }
  if (key.includes('buster')) return STATUS_ICON_URLS.buster_up;
  if (key.includes('arts')) return STATUS_ICON_URLS.arts_up;
  if (key.includes('quick')) return STATUS_ICON_URLS.quick_up;
  if (key.includes('crit_dmg') || key.includes('crit_damage')) return STATUS_ICON_URLS.crit_dmg;
  if (key.includes('star')) return STATUS_ICON_URLS.crit_stars;
  if (key.includes('guts')) return STATUS_ICON_URLS.guts;
  if (key.includes('anti_purge_defense') || key.includes('anti_purge')) return STATUS_ICON_URLS.anti_purge_defense;
  if (key.includes('anti_purge_atk')) return STATUS_ICON_URLS.anti_purge_atk;
  if (key.includes('invincible') || key.includes('invuln')) return STATUS_ICON_URLS.invincible;
  if (key.includes('evade') || key.includes('evasion')) return STATUS_ICON_URLS.evade;
  if (key.includes('heal')) return STATUS_ICON_URLS.heal;
  if (key.includes('stun')) return STATUS_ICON_URLS.stun;
  if (key.includes('skill_seal')) return STATUS_ICON_URLS.skill_seal;
  if (key.includes('np_seal')) return STATUS_ICON_URLS.np_seal;
  if (key.includes('burn') || key.includes('curse') || key.includes('poison')) return STATUS_ICON_URLS.burn;

  return STATUS_ICON_URLS.buff_atk;
}
